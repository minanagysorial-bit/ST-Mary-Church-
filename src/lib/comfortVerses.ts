/**
 * Returns a deterministic, beautiful comfort verse for any date of the year (auto daily rotation)
 */
export function getDailyAutoVerse(date: Date = new Date()): ComfortVerseItem {
  // Day of year calculation (1 to 366)
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);

  const index = Math.abs(dayOfYear) % COMFORT_VERSES_REGISTRY.length;
  return COMFORT_VERSES_REGISTRY[index] || COMFORT_VERSES_REGISTRY[0];
}

/**
 * Returns a random comfort verse from the registry
 */
export function getRandomComfortVerse(): ComfortVerseItem {
  const index = Math.floor(Math.random() * COMFORT_VERSES_REGISTRY.length);
  return COMFORT_VERSES_REGISTRY[index];
}
