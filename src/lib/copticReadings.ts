/**
 * Intelligent Scriptural Text Resolver
 * Exact key match -> Segment match -> Book & Chapter matcher -> Contextual Chant Fallback
 */
export function getVerseText(refKey: string | undefined, defaultFallback: string): string {
  if (!refKey) return defaultFallback;

  // 1. Direct exact key match
  if (BIBLE_TEXT_DB[refKey]) {
    return BIBLE_TEXT_DB[refKey];
  }

  // 2. Exact match on split segments (if compound reference like "Psalms 65:11;Psalms 81:1")
  const segments = refKey.split(';');
  for (const seg of segments) {
    const trimmed = seg.trim();
    if (BIBLE_TEXT_DB[trimmed]) {
      return BIBLE_TEXT_DB[trimmed];
    }
  }

  // 3. Partial key match
  for (const [k, v] of Object.entries(BIBLE_TEXT_DB)) {
    if (refKey.includes(k) || k.includes(refKey)) {
      return v;
    }
  }

  // 4. Smart Psalm Chapter Matcher
  if (refKey.toLowerCase().includes('psalm')) {
    const match = refKey.match(/psalms?\s*(\d+)/i);
    if (match && match[1]) {
      const chapter = parseInt(match[1], 10);
      return generateDynamicPsalmChant(chapter, refKey);
    }
  }

  return defaultFallback;
}

