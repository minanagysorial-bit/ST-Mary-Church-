export const COPTIC_MONTHS = [
  'توت', 'بابه', 'هاتور', 'كيهك', 'طوبة', 'أمشير',
  'برمهات', 'برمودة', 'بشنس', 'بؤونة', 'أبيب', 'مسرى', 'النسيء'
];

/**
 * Calculates exact Coptic date from any Gregorian Date
 */
export function getCopticDate(date: Date = new Date()): CopticDateInfo {
  const gYear = date.getFullYear();
  const leapOffset = (gYear % 4 === 3) ? 1 : 0;
  
  const startTout = new Date(gYear, 8, 11 + leapOffset);
  let cYear: number;
  let cMonth: number;
  let cDay: number;

  if (date >= startTout) {
    cYear = gYear - 283;
    const diffDays = Math.floor((date.getTime() - startTout.getTime()) / (1000 * 60 * 60 * 24));
    cMonth = Math.floor(diffDays / 30);
    cDay = (diffDays % 30) + 1;
  } else {
    cYear = gYear - 284;
    const prevTout = new Date(gYear - 1, 8, 11 + ((gYear - 1) % 4 === 3 ? 1 : 0));
    const diffDays = Math.floor((date.getTime() - prevTout.getTime()) / (1000 * 60 * 60 * 24));
    cMonth = Math.floor(diffDays / 30);
    cDay = (diffDays % 30) + 1;
  }

  if (cMonth > 12) cMonth = 12;
  const cMonthName = COPTIC_MONTHS[cMonth] || 'مسرى';

  const gregorianFormatter = new Intl.DateTimeFormat('ar-EG', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  });

  const gregorianDateString = gregorianFormatter.format(date);
  const copticDateString = `${cDay} ${cMonthName} ${cYear} ش.`;

  // Determine Coptic Liturgical Season
  let seasonName = 'الأيام السنوية العادية';
  if (cMonthName === 'كيهك') seasonName = 'شهر كيهك المبارك (تسابيح ومدائح السيدة العذراء)';
  else if (cMonthName === 'طوبة' && (cDay === 11 || cDay === 12)) seasonName = 'عيد الغطاس المجيد وبرامون الغطاس';
  else if (cMonthName === 'كيهك' && (cDay === 28 || cDay === 29)) seasonName = 'عيد الميلاد المجيد';
  else if (cMonthName === 'مسرى' && cDay === 16) seasonName = 'عيد صعود جسد القديسة مريم العذراء';
  else if (cMonthName === 'مسرى' && cDay >= 1 && cDay < 16) seasonName = 'صوم السيدة العذراء مريم الطاهرة';
  else if (cMonthName === 'أبيب' && cDay === 5) seasonName = 'عيد الرسل الأطهار';
  else if (cMonthName === 'توت' && cDay === 1) seasonName = 'عيد النيروز المجيد (رأس السنة القبطية الشهداء)';
  else if (cMonthName === 'توت' && (cDay >= 17 && cDay <= 19)) seasonName = 'عيد الصليب المجيد';
  else if (cMonthName === 'برمهات' && cDay === 29) seasonName = 'عيد البشارة المجيد';

  return {
    copticDay: cDay,
    copticMonthName: cMonthName,
    copticMonthIndex: cMonth,
    copticYear: cYear,
    gregorianDateString,
    copticDateString,
    seasonName
  };
}

