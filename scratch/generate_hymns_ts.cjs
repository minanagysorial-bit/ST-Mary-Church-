const hymnsData = items.map((item, idx) => {
  // clean up ID from trailing -0
  const cleanId = item.id.replace(/-0$/, '');
  return {
    id: `drive_hymn_${idx + 1}`,
    title: item.name,
    category: getCategory(item.name),
    drive_url: `https://drive.google.com/file/d/${cleanId}/view?usp=sharing`,
    lyrics_snippet: getSnippet(item.name),
    created_at: '2026-08-30'
  };
});

fs.writeFileSync('scratch/hymns_generated.json', JSON.stringify(hymnsData, null, 2));
